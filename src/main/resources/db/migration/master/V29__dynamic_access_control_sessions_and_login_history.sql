-- ============================================================
-- V29: Dynamic access control (DB-driven RBAC), subscription-feature
--      gated permissions, user sessions and unified login history.
--
-- After this migration the database is the single source of truth for
-- roles and permissions. New permissions / roles / grants are plain
-- INSERTs and take effect without a deploy (cache TTL, default 60s).
-- See docs/security/DYNAMIC_ACCESS_CONTROL.md.
-- ============================================================

-- 1. Permission catalog -------------------------------------------------------
CREATE TABLE access_permission (
    id               UUID         NOT NULL DEFAULT gen_random_uuid(),
    permission_code  VARCHAR(100) NOT NULL,
    name             VARCHAR(200) NOT NULL,
    description      TEXT,
    module_code      VARCHAR(50)  NOT NULL DEFAULT 'GENERAL',
    scope            VARCHAR(20)  NOT NULL DEFAULT 'SCHOOL',
    feature_code     VARCHAR(50),
    is_active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    version          BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_access_permission PRIMARY KEY (id),
    CONSTRAINT uq_access_permission_code UNIQUE (permission_code),
    CONSTRAINT chk_access_permission_code CHECK (permission_code ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT chk_access_permission_scope CHECK (scope IN ('PLATFORM', 'SCHOOL', 'COMMUNITY')),
    CONSTRAINT fk_access_permission_feature
        FOREIGN KEY (feature_code) REFERENCES subscription_feature(feature_code)
        ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX idx_access_permission_module  ON access_permission(module_code);
CREATE INDEX idx_access_permission_feature ON access_permission(feature_code);

COMMENT ON TABLE  access_permission IS 'Permission catalog. permission_code is the authority string used in @PreAuthorize(hasAuthority(...)).';
COMMENT ON COLUMN access_permission.scope IS 'PLATFORM = platform staff only; SCHOOL = may be granted inside school roles; COMMUNITY = community users';
COMMENT ON COLUMN access_permission.feature_code IS 'If set, school users only get this permission while the school has this subscription feature (or a sub-feature of this module) enabled';

-- 2. Roles (global when school_id IS NULL, school-specific otherwise) ---------
CREATE TABLE access_role (
    id                      UUID         NOT NULL DEFAULT gen_random_uuid(),
    role_code               VARCHAR(50)  NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    description             TEXT,
    scope                   VARCHAR(20)  NOT NULL,
    school_id               UUID,
    is_system               BOOLEAN      NOT NULL DEFAULT FALSE,
    grants_all_permissions  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    created_by              UUID,
    updated_by              UUID,
    version                 BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT pk_access_role PRIMARY KEY (id),
    CONSTRAINT chk_access_role_code CHECK (role_code ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT chk_access_role_scope CHECK (scope IN ('PLATFORM', 'SCHOOL', 'SCHOOL_PORTAL', 'COMMUNITY')),
    CONSTRAINT chk_access_role_school_scope CHECK (school_id IS NULL OR scope IN ('SCHOOL', 'SCHOOL_PORTAL')),
    CONSTRAINT chk_access_role_grants_all CHECK (NOT grants_all_permissions OR (school_id IS NULL AND scope = 'PLATFORM')),
    -- School custom roles may not reuse an account-type code (defence in depth; the API also rejects any global code)
    CONSTRAINT chk_access_role_custom_code CHECK (school_id IS NULL OR role_code NOT IN (
        'PLATFORM_SUPER_ADMIN', 'PLATFORM_ADMIN', 'PLATFORM_STAFF', 'COMMUNITY_ADMIN', 'COMMUNITY_ROLE_MANAGER',
        'COMMUNITY_MANAGER', 'FIELD_AGENT', 'SCHOOL_OWNER', 'SCHOOL_ADMIN', 'SCHOOL_STAFF', 'TEACHER', 'PRINCIPAL',
        'COORDINATOR', 'SUBJECT_TEACHER', 'ACCOUNTS', 'PARENT', 'STUDENT')),
    CONSTRAINT fk_access_role_school FOREIGN KEY (school_id) REFERENCES school(id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_access_role_global_code ON access_role(role_code) WHERE school_id IS NULL;
CREATE UNIQUE INDEX uq_access_role_school_code ON access_role(school_id, role_code) WHERE school_id IS NOT NULL;
CREATE INDEX idx_access_role_school ON access_role(school_id);

COMMENT ON TABLE  access_role IS 'Roles. school_id NULL = global/system role; non-null = custom role owned by that school';
COMMENT ON COLUMN access_role.grants_all_permissions IS 'Super-user flag: role holds every active permission, including ones inserted later';
COMMENT ON COLUMN access_role.is_system IS 'System roles back platform_user.platform_role account types and cannot be deleted';

-- 3. Role -> permission grants -----------------------------------------------
CREATE TABLE access_role_permission (
    id             UUID        NOT NULL DEFAULT gen_random_uuid(),
    role_id        UUID        NOT NULL,
    permission_id  UUID        NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_access_role_permission PRIMARY KEY (id),
    CONSTRAINT uq_access_role_permission UNIQUE (role_id, permission_id),
    CONSTRAINT fk_arp_role FOREIGN KEY (role_id) REFERENCES access_role(id) ON DELETE CASCADE,
    CONSTRAINT fk_arp_permission FOREIGN KEY (permission_id) REFERENCES access_permission(id) ON DELETE CASCADE
);

CREATE INDEX idx_arp_permission ON access_role_permission(permission_id);

-- 4. Additional role assignments per user (on top of platform_user.platform_role)
CREATE TABLE user_role_assignment (
    id           UUID        NOT NULL DEFAULT gen_random_uuid(),
    user_id      UUID        NOT NULL,
    role_id      UUID        NOT NULL,
    school_id    UUID,
    is_active    BOOLEAN     NOT NULL DEFAULT TRUE,
    valid_from   TIMESTAMPTZ,
    valid_until  TIMESTAMPTZ,
    notes        TEXT,
    assigned_by  UUID,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version      BIGINT      NOT NULL DEFAULT 0,

    CONSTRAINT pk_user_role_assignment PRIMARY KEY (id),
    CONSTRAINT uq_user_role_assignment UNIQUE (user_id, role_id),
    CONSTRAINT chk_ura_validity CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until > valid_from),
    CONSTRAINT fk_ura_user FOREIGN KEY (user_id) REFERENCES platform_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_ura_role FOREIGN KEY (role_id) REFERENCES access_role(id) ON DELETE CASCADE,
    CONSTRAINT fk_ura_school FOREIGN KEY (school_id) REFERENCES school(id) ON DELETE CASCADE
);

CREATE INDEX idx_ura_user   ON user_role_assignment(user_id);
CREATE INDEX idx_ura_role   ON user_role_assignment(role_id);
CREATE INDEX idx_ura_school ON user_role_assignment(school_id);

COMMENT ON TABLE user_role_assignment IS 'Extra roles per user (global or school custom roles). Primary role still comes from platform_user.platform_role';

-- 5. Per-user permission exceptions (explicit GRANT or DENY) -----------------
CREATE TABLE user_permission_override (
    id             UUID        NOT NULL DEFAULT gen_random_uuid(),
    user_id        UUID        NOT NULL,
    permission_id  UUID        NOT NULL,
    effect         VARCHAR(10) NOT NULL,
    reason         TEXT,
    valid_until    TIMESTAMPTZ,
    created_by     UUID,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_user_permission_override PRIMARY KEY (id),
    CONSTRAINT uq_user_permission_override UNIQUE (user_id, permission_id),
    CONSTRAINT chk_upo_effect CHECK (effect IN ('GRANT', 'DENY')),
    CONSTRAINT fk_upo_user FOREIGN KEY (user_id) REFERENCES platform_user(id) ON DELETE CASCADE,
    CONSTRAINT fk_upo_permission FOREIGN KEY (permission_id) REFERENCES access_permission(id) ON DELETE CASCADE
);

CREATE INDEX idx_upo_user ON user_permission_override(user_id);

COMMENT ON TABLE user_permission_override IS 'User-level exceptions. DENY always wins over role grants; GRANT adds a permission without a role';

-- 6. Sessions (one row per login / device) -----------------------------------
CREATE TABLE user_session (
    id                 UUID         NOT NULL DEFAULT gen_random_uuid(),
    user_id            UUID         NOT NULL,
    school_id          UUID,
    account_scope      VARCHAR(20)  NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    ip_address         VARCHAR(64),
    user_agent         VARCHAR(500),
    device_type        VARCHAR(20),
    browser            VARCHAR(50),
    operating_system   VARCHAR(50),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    last_seen_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    last_refreshed_at  TIMESTAMPTZ,
    expires_at         TIMESTAMPTZ  NOT NULL,
    ended_at           TIMESTAMPTZ,
    end_reason         VARCHAR(50),
    ended_by           UUID,

    CONSTRAINT pk_user_session PRIMARY KEY (id),
    CONSTRAINT chk_user_session_status CHECK (status IN ('ACTIVE', 'LOGGED_OUT', 'REVOKED', 'EXPIRED')),
    CONSTRAINT chk_user_session_scope CHECK (account_scope IN ('PLATFORM', 'SCHOOL', 'SCHOOL_PORTAL', 'COMMUNITY')),
    CONSTRAINT fk_user_session_user FOREIGN KEY (user_id) REFERENCES platform_user(id) ON DELETE CASCADE
);

CREATE INDEX idx_user_session_user_status ON user_session(user_id, status);
CREATE INDEX idx_user_session_school      ON user_session(school_id, status);

COMMENT ON TABLE user_session IS 'Server-side sessions. Access and refresh tokens carry the session id (sid); revoking a session invalidates its tokens immediately';

ALTER TABLE refresh_token
    ADD COLUMN IF NOT EXISTS session_id UUID;
ALTER TABLE refresh_token
    ADD CONSTRAINT fk_refresh_token_session FOREIGN KEY (session_id) REFERENCES user_session(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS idx_refresh_token_session ON refresh_token(session_id);

-- Refresh tokens issued before sessions existed cannot be tied to a session: retire them.
UPDATE refresh_token SET revoked = TRUE, revoked_at = NOW(), replaced_by_token_hash = 'MIGRATION_V29'
WHERE revoked = FALSE;

-- 7. Unified login history (platform, community and school users) ------------
CREATE TABLE login_history (
    id                UUID         NOT NULL DEFAULT gen_random_uuid(),
    user_id           UUID,
    email             VARCHAR(255),
    school_id         UUID,
    account_scope     VARCHAR(20),
    event_type        VARCHAR(30)  NOT NULL,
    failure_reason    VARCHAR(100),
    session_id        UUID,
    ip_address        VARCHAR(64),
    user_agent        VARCHAR(500),
    device_type       VARCHAR(20),
    browser           VARCHAR(50),
    operating_system  VARCHAR(50),
    correlation_id    VARCHAR(100),
    occurred_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_login_history PRIMARY KEY (id),
    CONSTRAINT chk_login_history_event CHECK (event_type IN (
        'LOGIN_SUCCESS', 'LOGIN_FAILED', 'ACCOUNT_LOCKED', 'LOGOUT', 'LOGOUT_ALL',
        'TOKEN_REFRESHED', 'SESSION_REVOKED', 'TOKEN_REUSE_DETECTED'
    )),
    CONSTRAINT fk_login_history_user FOREIGN KEY (user_id) REFERENCES platform_user(id) ON DELETE SET NULL
);

CREATE INDEX idx_login_history_user_time   ON login_history(user_id, occurred_at DESC);
CREATE INDEX idx_login_history_school_time ON login_history(school_id, occurred_at DESC);
CREATE INDEX idx_login_history_email       ON login_history(email);

